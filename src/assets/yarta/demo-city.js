/* Demo City Council: a fictional Victorian council for sales calls (Toby Field and Nigel Taylor).
   Every figure is illustrative, generated by the same seeded demo engine as the other demo organisations.
   Load after demo-data.js and sectors.js, and before portal.js.

   Add-only:
   - Appends Demo City Council and three demo people to window.YESDEMO. Nothing else in demo-data.js changes.
   - A browser that already holds a saved demo gets Demo City added to it. No other organisation, person,
     booking or setting is changed, and the storage key and version stay the same.
   - YESDEMO.resetCity() puts Demo City back to its starting state in this browser and touches nothing else.
   - Does nothing to stored data in live mode (a Firebase project configured). */
(function(X, S){
  if(!X || !X.ORGS || !X.USERS) return;
  var ID = 'demo-city', KEY = 'yes-es-portal-v3';
  if(X.ORGS.some(function(o){ return o.id===ID; })) return;   /* loaded twice: no-op */

  X.CITY_ID = ID;
  X.ORGS.push({id:ID,
    profile:{org_name:"Demo City Council", org_type:"Council", sector:"council", state:"VIC", residents:112000, employees:980, floor_area:84000, facilities:58, baseline_fy:"2024–25",
      target_emissions:40, target_renewable:80, target_diversion:75, target_fleet_ev:30, target_trees:8000, target_rehab_ha:24, target_participants:12000, target_native_ha:30,
      boundary:"Operational control", scope2_contract:"Accredited GreenPower or certified renewable contract", demo_note:"Fictional council. Every figure is illustrative."},
    gen:{seed:20240702, scale:2.3, start:"2024-07", end:"2026-10", verifiedTo:"2026-10", draft:false, contact:"Jamie Ellis",
      fuelDecline:.05, petrolDecline:.10, elecDecline:.04, gasDecline:.10, waterDecline:.03,
      renew:[["2000-01",0.25],["2025-07",0.55],["2026-07",0.75]],
      fleet:[
        ["2024-07",{vd:96,vp:128,vh:30,vphev:4,vbev:8,td:82,te:0,plant:130,evp:8,evs:12,solar:1100,solarSites:26,batt:0,stew:3}],
        ["2025-09",{vd:92,vp:112,vh:34,vphev:6,vbev:22,td:81,te:1,plant:128,evp:12,evs:20,solar:1450,solarSites:31,batt:250,stew:3}],
        ["2026-05",{vd:90,vp:98,vh:36,vphev:6,vbev:34,td:80,te:2,plant:128,evp:16,evs:26,solar:1600,solarSites:33,batt:250,stew:4}]],
      /* the four streams shown on sales calls lean a little heavier than the shire's */
      mix:{steel_t:1.25, alu_t:1.2, mattress_n:0.9, timber_t:1.35, timber_treated_t:1.2, green_t:1.3},
      draftFields:[]}});

  X.USERS.push(
    {id:"u-toby", name:"Toby Field", title:"Demo login · Recycle Group", email:"toby.field@demo-city.example", role:"customer", org:ID},
    {id:"u-nigel", name:"Nigel Taylor", title:"Demo login · Recycle Group", email:"nigel.taylor@demo-city.example", role:"customer", org:ID},
    {id:"u-jamie-city", name:"Jamie Ellis", title:"Sustainability Officer (fictional)", email:"jamie.ellis@demo-city.example", role:"customer", org:ID});
  var CITY_USERS = ["u-toby","u-nigel","u-jamie-city"];

  /* Issued dates (the 20th of the following month), onboarding and subscription, so Demo City looks the same
     whether it arrives in a fresh demo or is added to one saved earlier. */
  function stamp(o, i){
    if(!o) return o;
    o.records.forEach(function(r){ if(r.status==='verified' && !r.issuedAt){ var p=r.month.split('-'), y=+p[0], m=+p[1]; if(m===12){ y++; m=1; } else m++; r.issuedAt=y+'-'+(m<10?'0':'')+m+'-20'; r.issuedBy='Chris Walker'; } });
    if(!o.onboarding){ var done={}; ((S&&S.ONBOARDING)||[]).forEach(function(st){ done[st.k]={at:'2024-06-28', by:'Yarta team'}; }); o.onboarding={start:'2024-06-03', done:done, notes:[]}; }
    if(!o.subscription) o.subscription={status:'active', foundation:false, start:'2024-06-03', termMonths:12, monthlyOverride:'', estFee:0, estStatus:'waived', notes:'Demo council (fictional)'};
    if(!o.plan) o.plan={off:{}};
    return o;
  }
  var build0 = X.build;
  X.build = function(){ var s = build0.apply(this, arguments); stamp(s.orgs[ID]); return s; };
  function freshCity(){ return build0().orgs[ID]; }

  function live(){ return !!(window.YARTA_FIREBASE || (window.YARTA_LIVE && window.YARTA_LIVE.enabled)); }
  function read(){ try{ var s=JSON.parse(localStorage.getItem(KEY)); return (s && s.v===6 && s.orgs && s.users) ? s : null; }catch(e){ return null; } }
  function write(s){ try{ localStorage.setItem(KEY, JSON.stringify(s)); return true; }catch(e){ return false; } }
  function addPeople(s){ X.USERS.forEach(function(u){ if(u.org===ID && !s.users.some(function(x){ return x.id===u.id; })) s.users.push(JSON.parse(JSON.stringify(u))); }); }
  function addCity(s){
    s.orgs[ID] = stamp(freshCity()); addPeople(s);
  }

  /* a saved demo from before Demo City existed: add it, change nothing else */
  if(!live()){ var saved = read(); if(saved && !saved.orgs[ID]){ addCity(saved); write(saved); } }

  /* Put Demo City back to how it started, in this browser only. Other organisations, people, bookings,
     providers and settings are left exactly as they are. Returns true when done. */
  X.resetCity = function(){
    if(live()) return false;
    var s = read(); if(!s) return true;   /* nothing saved yet: the next page load builds a fresh demo with Demo City in it */
    s.users = s.users.filter(function(u){ return u.org!==ID || CITY_USERS.indexOf(u.id)>=0; });   /* colleagues added during a call go */
    if(s.session && !s.users.some(function(u){ return u.id===s.session.user; })) s.session=null;
    addCity(s);
    s.bookings = (s.bookings||[]).filter(function(b){ return b.org!==ID; });
    if(s.outbox) s.outbox = s.outbox.filter(function(m){ return m.org!==ID; });
    if(s.audit) s.audit = s.audit.filter(function(a){ return a.org!==ID; });
    if(s.gapLog) s.gapLog = s.gapLog.filter(function(g){ return g.org!==ID; });
    if(s.seen) CITY_USERS.forEach(function(id){ delete s.seen[id]; });
    var ok = write(s);
    /* evidence files attached to Demo City during a call (keys start "demo-city/" or "inbox/demo-city/") */
    try{ var q=indexedDB.open('yes-es-evidence',1); q.onupgradeneeded=function(){ q.result.createObjectStore('files'); };
      q.onsuccess=function(){ try{ var db=q.result, tx=db.transaction('files','readwrite'), st=tx.objectStore('files'), c=st.openCursor();
        c.onsuccess=function(){ var cur=c.result; if(!cur) return; var k=String(cur.key); if(k.indexOf(ID+'/')===0 || k.indexOf('inbox/'+ID+'/')===0) cur.delete(); cur.continue(); }; }catch(e){} }; }catch(e){}
    return ok;
  };
})(window.YESDEMO, window.YESS);
